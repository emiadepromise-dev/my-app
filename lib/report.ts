function findingsHtml(findings: Finding[]): string {
  if (findings.length === 0) return '<p style="font-size: 13px; color: #6b7280;">No findings.</p>';

  const sorted = [...findings].sort(
    (a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity)
  );

  return sorted
    .map(
      (f) => `
    <div class="finding">
      <div class="finding-header">
        <span class="badge" style="background: ${severityColor(f.severity)}">${f.severity.toUpperCase()}</span>
        <span class="finding-title">${escapeHtml(f.title)}</span>
      </div>
      <div class="finding-desc">${escapeHtml(f.description)}</div>
      ${f.evidence ? `<div class="finding-evidence">${escapeHtml(f.evidence)}</div>` : ""}
      <div class="finding-rec"><strong>Recommendation:</strong> ${escapeHtml(f.recommendation)}</div>
    </div>`
    )
    .join("");
}

export function generateWebsiteReport(data: WebsiteScanResult): string {
  const sortedFindings = [...data.findings].sort(
    (a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity)
  );
  const counts = SEVERITY_ORDER.map(
    (s) => `${s.charAt(0).toUpperCase() + s.slice(1)}: ${sortedFindings.filter((f) => f.severity === s).length}`
  ).join(" | ");

  let html = reportHeader("Website Security Report");

  html += `
<div class="brand"><span style="font-size:20px;">🛡</span><h1>CyberYoshi</h1></div>
<div class="title">Website Security Report</div>
<div class="meta">Target: ${escapeHtml(data.url)} &bull; Scanned: ${escapeHtml(data.scannedAt)}</div>

<div class="stat-grid">
  <div class="stat-box"><div class="stat-value">${data.score}</div><div class="stat-label">Security Score / 100</div></div>
  <div class="stat-box"><div class="stat-value">${data.findings.length}</div><div class="stat-label">Findings</div></div>
  <div class="stat-box"><div class="stat-value">${data.crawl.pagesVisited.length}</div><div class="stat-label">Pages Crawled</div></div>
  <div class="stat-box"><div class="stat-value">${data.crawl.brokenLinks.length}</div><div class="stat-label">Broken Links</div></div>
</div>
<p style="font-size: 13px; color: #6b7280; margin-bottom: 20px;">${counts}</p>

<div class="section">
  <div class="section-title">Security Findings</div>
  ${findingsHtml(data.findings)}
</div>

<div class="section">
  <div class="section-title">Crawl Results</div>
  <table>
    <thead><tr><th>Page</th></tr></thead>
    <tbody>${data.crawl.pagesVisited.map((p) => `<tr><td style="font-size:12px;word-break:break-all;">${escapeHtml(p)}</td></tr>`).join("")}</tbody>
  </table>
</div>`;

  if (data.technologies.technologies.length > 0) {
    html += `
<div class="section">
  <div class="section-title">Detected Technologies</div>
  <p style="font-size: 13px;">${data.technologies.technologies.map((t) => escapeHtml(t.name)).join(", ")}</p>
</div>`;
  }

  if (data.cookies.cookies.length > 0) {
    html += `
<div class="section">
  <div class="section-title">Cookies</div>
  <table>
    <thead><tr><th>Name</th><th>Secure</th><th>HttpOnly</th><th>SameSite</th></tr></thead>
    <tbody>${data.cookies.cookies.map((c) => `<tr><td style="font-family:monospace">${escapeHtml(c.name)}</td><td>${c.secure ? "Yes" : "No"}</td><td>${c.httpOnly ? "Yes" : "No"}</td><td>${escapeHtml(c.sameSite || "None")}</td></tr>`).join("")}</tbody>
  </table>
</div>`;
  }

  html += reportFooter();
  return html;
}

export function generatePortReport(data: PortScanResult): string {
  const sortedPorts = [...data.ports].sort((a, b) => {
    const order = { open: 0, filtered: 1, closed: 2, error: 3 };
    return order[a.status] - order[b.status] || a.port - b.port;
  });

  let html = reportHeader("Port Scan Report");

  html += `
<div class="brand"><span style="font-size:20px;">🛡</span><h1>CyberYoshi</h1></div>
<div class="title">Port Scan Report</div>
<div class="meta">Target: ${escapeHtml(data.target)} &bull; Scanned: ${escapeHtml(data.scannedAt)}</div>

<div class="stat-grid">
  <div class="stat-box"><div class="stat-value" style="color:#22c55e">${data.openPorts}</div><div class="stat-label">Open Ports</div></div>
  <div class="stat-box"><div class="stat-value">${data.closedPorts}</div><div class="stat-label">Closed Ports</div></div>
  <div class="stat-box"><div class="stat-value">${data.filteredPorts}</div><div class="stat-label">Filtered Ports</div></div>
  <div class="stat-box"><div class="stat-value">${data.ports.length}</div><div class="stat-label">Total Scanned</div></div>
</div>

<div class="section">
  <div class="section-title">Port Results</div>
  <table>
    <thead><tr><th>Port</th><th>Status</th><th>Service</th><th>Risk</th><th>Details</th></tr></thead>
    <tbody>
      ${sortedPorts
        .map(
          (p) => `<tr>
            <td style="font-family:monospace;font-weight:600">${p.port}</td>
            <td><span class="badge" style="background:${p.status === "open" ? "#ef4444" : p.status === "filtered" ? "#6b7280" : "#9ca3af"}">${p.status.toUpperCase()}</span></td>
            <td>${escapeHtml(p.service)}</td>
            <td>${p.status === "open" ? p.risk : "—"}</td>
            <td style="font-size:12px;color:#6b7280">${p.status === "open" ? escapeHtml(p.riskReason) : ""}</td>
          </tr>`
        )
        .join("")}
    </tbody>
  </table>
</div>`;

  html += reportFooter();
  return html;
}

export function generateFileHashReport(data: FileHashReportData): string {
  let html = reportHeader("File Hash Report");

  html += `
<div class="brand"><span style="font-size:20px;">🛡</span><h1>CyberYoshi</h1></div>
<div class="title">File Hash Report</div>
<div class="meta">File: ${escapeHtml(data.fileName)} &bull; Size: ${formatSize(data.fileSize)}</div>

<div class="stat-grid">
  <div class="stat-box"><div class="stat-value" style="font-size:18px">${Object.keys(data.hashes).length}</div><div class="stat-label">Hash Algorithms</div></div>
  <div class="stat-box"><div class="stat-value" style="color:${data.verified === true ? "#22c55e" : data.verified === false ? "#ef4444" : "#6b7280"};font-size:18px">${data.verified === true ? "Verified" : data.verified === false ? "Not Verified" : "N/A"}</div><div class="stat-label">Verification</div></div>
</div>

<div class="section">
  <div class="section-title">Generated Hashes</div>
  ${Object.entries(data.hashes)
    .map(
      ([algo, hash]) => `
    <div class="hash-row">
      <div class="hash-label">${algo.toUpperCase()}</div>
      <div class="hash-value">${escapeHtml(hash)}</div>
    </div>`
    )
    .join("")}
</div>`;

  html += reportFooter();
  return html;
}

export function openReport(html: string): void {
  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  window.open(url, "_blank");
}

export function downloadReport(html: string, filename: string): void {
  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
