import type { WebsiteScanResult, Finding, Severity } from "@/lib/scanner/types";
import type { PortScanResult } from "@/lib/scanner/port-types";

interface FileHashReportData {
  fileName: string;
  fileSize: number;
  hashes: Record<string, string>;
  verified: boolean | null;
}

const SEVERITY_ORDER: Severity[] = ["critical", "high", "medium", "low", "informational"];

function formatSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1048576) return `${(bytes / 1024).toFixed(1)} KB`;
  if (bytes < 1073741824) return `${(bytes / 1048576).toFixed(1)} MB`;
  return `${(bytes / 1073741824).toFixed(1)} GB`;
}

function severityColor(severity: Severity): string {
  switch (severity) {
    case "critical": return "#ef4444";
    case "high": return "#f97316";
    case "medium": return "#eab308";
    case "low": return "#3b82f6";
    case "informational": return "#6b7280";
  }
}

function escapeHtml(str: string): string {
  return str.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

